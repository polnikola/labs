#%% Получение характеристик фильтров
""" Получение характеристик фильтров
- Построить ИХ фильтров на одном графике (показать отсчёты до 0)
- Построить АЧХ фильтровб на одном графике
- Построить ФЧХ фильтровб на одном графике
"""
def delta(N: int, m: int = 0):
	"""
	Генерирует дискретный δ-импульс (единичный импульс)	
	Parameters:
	N : int
	    Длина выходного массива
	m : int
	    Позиция единичного импульса (0 <= m < N)	
	Returns:
	numpy.ndarray
	    Массив длины N с единицей на позиции m и нулями в остальных позициях
	"""
	d = np.zeros((N,))
	d[int(m)] = 1
	return d


