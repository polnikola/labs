#%% Демонстрация растекания спектра
""" Демонстрация растекания спектра

Блок демонстрирует растекание спектра и его причины.
Задаётся множество частот, которые соответствуют целы и
дробным отсчётам цифрового спектра.
Демонстрируется как сам сигнал, так и предполагаемый разрыв фазы
при периодическом повторении сигнала. В этом же окне демонстрируется 
изменение спектра связанное с разрывом фазы на границах.
Далее в динамике продемонстрировано изменение спектра при изменении частоты.
"""
f_d = 1e9			# частота дискретизации, Гц
t_d = 1/f_d			# период дискретизации
n_samples = 200							# число отсчётов в сигнале
use_window = True	# использовать окно?

t_ax = np.arange(n_samples)*t_d			# ось времени
f_ax = np.fft.rfftfreq(n_samples,t_d)	# ось частоты
ks = (10+np.arange(500)/100)	# частотные отсчёты для синусойд
f0s=f_d /n_samples * ks				 	# частоты синусойд, Гц
n2W = (f_d * n_samples)					# коэффициент нормировки СПМ (|БПФ|²)

# Creating a window
fig = plt.figure(f'Растекание спектра ({"с окном" if use_window else "Без окна"})')
fig.clf()
axs = fig.subplots(2,2)

# Демонстрация 
for i in range(5):
	f0=f0s[i*25]							# выбор каждой n-ой частоты
	
	x =  np.cos(2*np.pi*f0*t_ax)					# генерация сигнала
	if use_window: 	x *= np.hamming(x.shape[-1])	# домножить на окно

	X = np.abs(rfft(x))**2 / n2W

	pt(x=t_ax*1e9, y=x+2*i, 
		names=[f'{ks[i*25]}/N'],
		y_lims=[-2,12], x_label='Время, нс', 
		title='Сигнал', ax=axs[0,0])
	pt(x=(t_ax-t_ax[50])[:100]*1e9, y=np.roll(x, 50)[:100]+2*i, 
		names=[f'{ks[i*25]}/N'],
		y_lims=[-2,12], x_label='Время, нс', 
		title='Граница периодического сигнала', ax=axs[0,1])
	pt(x=f_ax/1e6, y=X, names=[f'{ks[i*25]}/N'], 
		x_label='Частота, МГц', y_label='СПМ, Вт/Гц', x_lims=[0,120], 
		title='ДПФ сигнала (дискретный спектр)', ax=axs[1,0])
	pt(x=f_ax/1e6, y=10*np.log(X), names=[f'{ks[i*25]}/N'], 
		x_label='Частота, МГц', y_label='СПМ, дБВт/Гц', x_lims=[0,120], 
		title='ДПФ сигнала (дискретный спектр)', ax=axs[1,1])


#%% Анимация растекания спектра 
""" Анимация растекания спектра """
Y=[]				# контейнер для спектра
for f0 in f0s:
	x = np.cos(2*np.pi*f0*t_ax)				# генерация сигнала
	y = np.abs(DFT(x, window=use_window))**2 / n2W 	# вычислить спектр и нормировать его
	Y.append(y)		# сохранить для анимации

fig = plt.figure('Изменеие частоты')
fig.clf()
run_animation(Y, f_ax/1e6, titles=[f'Частота синусойды (в отсчётах): {k:05.2f} / {n_samples}' for k in ks],
				x_label='Частота, МГц', fps=24, ax=fig)


